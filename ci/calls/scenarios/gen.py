#!/usr/bin/env python3
"""Writes the calling scenarios (SIPp reads pcap paths and auth at load time, so each variant
is its own straight-line file):

  call_phone.xml        a phone (digest challenge, then -au/-ap), talks silently
  call_phone_audio.xml  the same, playing SIPp's G.711 sample (voicemail)
  call_carrier.xml      a carrier (no auth)

Each places a call to -set to N in -set domain D, logs "RESULT <code>" (200 or the refusal)
and, when answered, hangs up after -d ms."""
import os

FINALS = ["401", "403", "404", "408", "480", "484", "486", "487", "488", "500", "502", "503", "504", "603"]
LOG = ('<action><ereg regexp="^SIP/2.0 ([0-9]{3})" search_in="msg" check_it="true" '
       'assign_to="all,code" /><log message="RESULT [$code]" /></action>')
SDP = """v=0
o=- 1 1 IN IP[local_ip_type] [local_ip]
s=-
c=IN IP[media_ip_type] [media_ip]
t=0 0
m=audio [media_port] RTP/AVP 8 0 101
a=rtpmap:8 PCMA/8000
a=rtpmap:0 PCMU/8000
a=rtpmap:101 telephone-event/8000
a=sendrecv"""


def invite(cseq, auth):
    return f"""  <send retrans="500"><![CDATA[
INVITE sip:[$to]@[$domain] SIP/2.0
Via: SIP/2.0/[transport] [local_ip]:[local_port];branch=[branch]
From: <sip:[service]@[$domain]>;tag=[pid]uac[call_number]
To: <sip:[$to]@[$domain]>
Call-ID: [call_id]
CSeq: {cseq} INVITE
Contact: <sip:[service]@[local_ip]:[local_port]>
{"[authentication]" + chr(10) if auth else ""}Max-Forwards: 70
Content-Type: application/sdp
Content-Length: [len]

{SDP}
]]></send>"""


def ack_negative(cseq):
    return f"""  <send><![CDATA[
ACK sip:[$to]@[$domain] SIP/2.0
[last_Via:]
From: <sip:[service]@[$domain]>;tag=[pid]uac[call_number]
[last_To:]
Call-ID: [call_id]
CSeq: {cseq} ACK
Max-Forwards: 70
Content-Length: 0

]]></send>"""


def in_dialog(method, cseq_line):
    return f"""  <send{' retrans="500"' if method == "BYE" else ""}><![CDATA[
{method} [next_url] SIP/2.0
Via: SIP/2.0/[transport] [local_ip]:[local_port];branch=[branch]
[routes]
From: <sip:[service]@[$domain]>;tag=[pid]uac[call_number]
[last_To:]
Call-ID: [call_id]
{cseq_line}
Max-Forwards: 70
Content-Length: 0

]]></send>"""


def scenario(name, auth, audio):
    cseq = 2 if auth else 1
    x = ['<?xml version="1.0" encoding="ISO-8859-1" ?>',
         "<!-- Generated by gen.py; edit that instead. -->",
         f'<scenario name="{name}">', '  <Global variables="to,domain" />', invite(1, False)]
    if auth:
        x += ['  <recv response="100" optional="true" />',
              '  <recv response="407" auth="true" optional="true" next="challenged" />',
              '  <recv response="401" auth="true" />', '  <label id="challenged" />',
              ack_negative(1), invite(2, True)]
    x += ['  <recv response="100" optional="true" />', '  <recv response="180" optional="true" />',
          '  <recv response="183" optional="true" />']
    x += [f'  <recv response="{c}" optional="true" next="refused">{LOG}</recv>' for c in FINALS]
    x += [f'  <recv response="200" rrs="true">{LOG}</recv>', in_dialog("ACK", f"CSeq: {cseq} ACK")]
    if audio:
        x.append('  <nop><action><exec play_pcap_audio="/usr/share/sip-tester/g711a.pcap" /></action></nop>')
    x += ["  <pause />", in_dialog("BYE", "CSeq: 10 BYE"), '  <recv response="200" next="end" />',
          '  <label id="refused" />', ack_negative(cseq), '  <label id="end" />', "</scenario>", ""]
    return "\n".join(x)


here = os.path.dirname(os.path.abspath(__file__))
for name, auth, audio in [("call_phone", True, False), ("call_phone_audio", True, True), ("call_carrier", False, False)]:
    open(os.path.join(here, name + ".xml"), "w").write(scenario(name, auth, audio))
